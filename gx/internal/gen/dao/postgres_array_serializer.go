package dao

import (
	"fmt"
	"os"
	"path/filepath"
)

const postgresArraySerializerSource = `// Code generated by Gonex CLI tool. DO NOT EDIT.

package entity

import (
	"context"
	"fmt"
	"reflect"
	"sync"

	"github.com/jackc/pgx/v5/pgtype"
	"gorm.io/gorm/schema"
)

const pgArraySerializerName = "pgarray"

var pgArrayTypeMaps = sync.Pool{
	New: func() interface{} {
		return pgtype.NewMap()
	},
}

type pgArraySerializer struct{}

func init() {
	schema.RegisterSerializer(pgArraySerializerName, pgArraySerializer{})
}

func (pgArraySerializer) Value(
	_ context.Context,
	_ *schema.Field,
	_ reflect.Value,
	fieldValue interface{},
) (interface{}, error) {
	if fieldValue == nil {
		return nil, nil
	}
	value := reflect.ValueOf(fieldValue)
	if value.Kind() != reflect.Slice {
		return nil, fmt.Errorf("pgarray serializer requires a slice, got %T", fieldValue)
	}
	return fieldValue, nil
}

func (pgArraySerializer) Scan(
	ctx context.Context,
	field *schema.Field,
	dst reflect.Value,
	dbValue interface{},
) error {
	target := reflect.New(field.FieldType)
	if dbValue == nil {
		field.ReflectValueOf(ctx, dst).Set(target.Elem())
		return nil
	}

	postgresTypeName := field.TagSettings["PGARRAY"]
	if postgresTypeName == "" {
		return fmt.Errorf("pgarray serializer field %s is missing pgarray type metadata", field.Name)
	}
	typeMap := pgArrayTypeMaps.Get().(*pgtype.Map)
	defer pgArrayTypeMaps.Put(typeMap)

	postgresType, ok := typeMap.TypeForName(postgresTypeName)
	if !ok {
		return fmt.Errorf("pgarray serializer does not recognize PostgreSQL type %q for field %s", postgresTypeName, field.Name)
	}

	var source []byte
	switch value := dbValue.(type) {
	case string:
		source = []byte(value)
	case []byte:
		source = value
	default:
		return fmt.Errorf("pgarray serializer cannot scan %T into field %s", dbValue, field.Name)
	}

	if err := typeMap.Scan(
		postgresType.OID,
		pgtype.TextFormatCode,
		source,
		target.Interface(),
	); err != nil {
		return fmt.Errorf("scan PostgreSQL array %q into field %s: %w", postgresTypeName, field.Name, err)
	}
	field.ReflectValueOf(ctx, dst).Set(target.Elem())
	return nil
}
`

func writePostgresArraySerializer(root string) error {
	if err := os.MkdirAll(root, 0o755); err != nil {
		return fmt.Errorf("create PostgreSQL array serializer directory %s: %w", root, err)
	}
	path := filepath.Join(root, "pgarray_serializer.gen.go")
	if err := os.WriteFile(path, []byte(postgresArraySerializerSource), 0o644); err != nil {
		return fmt.Errorf("write PostgreSQL array serializer %s: %w", path, err)
	}
	return nil
}
